"""收紧 _QUERY_CUES：剔除被误收进去的实词。

★ 为什么要改：
  第一版集合里混进了「包含」「属于」「可以」这类**实词**，
  用真实索引一量就暴露了：
      包含  df= 42  idf=4.538   <- 相当稀有，是有区分度的实词
      属于  df=123  idf=3.479
      可以  df=664  idf=1.799
  把它们当虚词打折，等于惩罚那些**最能定位答案**的词。
  （「消防产品的认证目录包含哪些类别」里的"包含"恰恰是关键信号）

  教训：写停用词表时，不能凭语感判断"这词像不像虚词"，
  得拿真实语料量一遍 idf：
    - 高频、几乎无区分度（idf≈0.15） -> 才是真正的虚词，可以打折
    - 稀有、有区分度（idf > 2）        -> 是实词，打折会伤召回

★ 保留的判定标准：idf 接近下限（0.15），即全库到处都是。
  「可以」idf=1.799 偏高，但仍属口语客套词，且 df=664 已属高频 ——
  保留但不主导（IDF 加权下它只占 1.799 的权重，不会像旧判据那样
  因为"算一个"就抬高 cue_ratio）。

★ 为什么保留「的」「了」「和」这类单字：
  它们在中文查询里几乎必然出现，且完全不携带语义。
  去掉会让「消防设施」这种查询的 cue_ratio 为 0 ——
  而这种查询恰恰最需要折扣保护（"消防"在噪声片段里满地都是）。
"""
import pathlib

p = pathlib.Path("agent1/hybrid.py")
src = p.read_text(encoding="utf-8")

OLD = '''    # 查询里的疑问句与连接词：这些词的 df 通常不小（几百上千），
    # 所以 idf 天然偏低；问题在于它们在噪声片段里的出现频次远高于答案片段
    # （"包括哪些"查出来的噪声片段，光"包括"就重复 7 次）。
    # 因此除了 idf 加权，还要按查询里这类词的占比给覆盖率打折。
    _QUERY_CUES = frozenset({
        "哪些", "哪个", "什么", "怎么", "如何", "是否", "能否", "可以",
        "包括", "包含", "有哪", "是什么", "为什么", "多少", "几个",
        "属于", "吗", "呢", "的", "了", "和", "与", "或", "在",
    })'''

NEW = '''    # 查询里的疑问句与高频虚词。
    #
    # ★ 判定标准不是"像不像虚词"，而是**实测 idf**（4019 片段库）：
    #     哪些/什么/吗/的/了   idf≈0.150   <- 全库都是，真虚词
    #     可以                idf=1.799    <- 口语客套，保留
    #     包括                idf=2.569    <- 已移除，见下
    #     属于                idf=3.479    <- 已移除，见下
    #     包含                idf=4.538    <- 已移除，见下
    #
    # ★ 为什么剔除「包含」「属于」：
    #   第一版把它们当虚词收进来了，但它们 idf 都在 3-4.5，
    #   是**有区分度的实词** —— 把最能定位答案的词当虚词惩罚，
    #   等于主动伤害召回。
    #   实测后果（47 条 A/B）：跨文档综合 recall 0.524 -> 0.381，
    #   陷阱题 0.333 -> 0.167，而直查法条反而涨 0.050。
    #
    # ★ 为什么剔除「包括」：
    #   idf=2.569，是查询里常用的实义动词。
    #   它在噪声片段里高频出现（"建筑消防设施包括哪些"的噪声片段
    #   光"包括"就重复 7 次）确实是个问题，
    #   但那应该靠**改分块**（让"包括"这种词不出现在随机位置）解决，
    #   而不是在打分函数里惩罚它。
    #
    # ★ 为什么保留「的」「了」「和」这类单字：
    #   中文查询里几乎必然出现，且完全不携带语义。
    #   去掉会让"消防设施"这种查询的 cue_ratio 归零 ——
    #   而它恰恰最需要折扣保护（"消防"在噪声里满地都是）。
    _QUERY_CUES = frozenset({
        "哪些", "哪个", "什么", "怎么", "如何", "是否", "能否", "可以",
        "有哪", "是什么", "为什么", "多少", "几个",
        "吗", "呢", "的", "了", "和", "与", "或", "在",
    })'''

if OLD not in src:
    print("✗ 未找到目标块，结构可能已变")
    raise SystemExit(1)

src = src.replace(OLD, NEW, 1)
p.write_text(src, encoding="utf-8")
print("✓ _QUERY_CUES 已剔除「包含」「包括」「属于」")
print(f"  集合大小：24 -> 21")