    def extract(self, text):
        if not text:
            return {}
        result = {}
        for category, pattern in self.PATTERNS.items():
            matches = re.findall(pattern, text)
            if matches:
                result[category] = list(dict.fromkeys(matches))
        names = self._extract_names(text)
        if names:
            result["人名"] = names
        return result

    def _extract_names(self, text):
        candidates = re.findall(r'[\u4e00-\u9fa5]{2,4}', text)
        names = [c for c in candidates
                 if c[0] in self.SURNAMES and c not in self.STOPWORDS]
        return list(dict.fromkeys(names))

